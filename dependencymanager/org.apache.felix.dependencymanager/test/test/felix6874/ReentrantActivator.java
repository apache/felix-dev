package test.felix6874;

import org.apache.felix.dm.ComponentExecutorFactory;
import org.apache.felix.dm.DependencyManager;
import org.osgi.framework.Bundle;
import org.osgi.framework.BundleActivator;
import org.osgi.framework.BundleContext;
import org.osgi.framework.ServiceFactory;
import org.osgi.framework.ServiceRegistration;

/**
 * Activator of the bundle generated by FELIX6874_ParallelStartTest to test a re-entrant call to the
 * service registry cache: it registers a ComponentExecutorFactory as a ServiceFactory, whose
 * getService() method creates a DependencyManager.
 *
 * When the DependencyManager bundle is started afterwards, its Activator tracks the
 * ComponentExecutorFactory services and calls getService() from its start method: our getService()
 * is then called on the Activator thread, while the DependencyManager bundle is STARTING, and the
 * DependencyManager it creates calls back the service registry cache.
 *
 * Each bundle has its own copy of this class (own class loader): the test reads the static fields
 * below using Bundle.loadClass().
 */
public class ReentrantActivator implements BundleActivator {

    /** true once our ServiceFactory has created its DependencyManager */
    public static volatile boolean s_called;

    /** the state of the DependencyManager bundle when our ServiceFactory has been called */
    public static volatile int s_dmState;

    /**
     * true if the DependencyManager created by our ServiceFactory uses the service registry cache
     */
    public static volatile boolean s_cacheUsed;

    /** the exception thrown when our ServiceFactory has created its DependencyManager, or null */
    public static volatile Throwable s_failure;

    @Override
    public void start(BundleContext context) throws Exception {
        context.registerService(ComponentExecutorFactory.class.getName(), new ServiceFactory<Object>() {
            @Override
            public Object getService(Bundle bundle, ServiceRegistration<Object> registration) {
                try {
                    // bundle is the DependencyManager bundle, which gets the service
                    s_dmState = bundle.getState();
                    DependencyManager manager = new DependencyManager(context);
                    s_cacheUsed = manager.getBundleContext() != context;
                } catch (Throwable e) {
                    s_failure = e;
                }
                s_called = true;
                // no executor: components are handled as usual
                ComponentExecutorFactory factory = component -> null;
                return factory;
            }

            @Override
            public void ungetService(Bundle bundle, ServiceRegistration<Object> registration, Object service) {
            }
        }, null);
    }

    @Override
    public void stop(BundleContext context) throws Exception {
    }
}
