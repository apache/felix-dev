package test.felix6874;

import java.util.Hashtable;

import org.apache.felix.dm.DependencyActivatorBase;
import org.apache.felix.dm.DependencyManager;
import org.osgi.framework.BundleContext;

/**
 * Activator of the user bundles generated by FELIX6874_ParallelStartTest. DependencyActivatorBase.start()
 * creates a DependencyManager, which initializes the service registry cache.
 *
 * If the "felix6874.components" framework property is "true", the activator registers a Runnable service with a
 * "user.bundle" property, and a client component depending on it with a "(user.bundle=<bundle id>)" filter, which is
 * served by the "objectClass,user.bundle" filter index (when enabled). Else, it only creates its DependencyManager.
 *
 * Each user bundle has its own copy of this class (own class loader): the test reads the static fields below
 * using Bundle.loadClass().
 */
public class UserActivator extends DependencyActivatorBase {

    /** framework property: "true" if the activator must add its components */
    public static final String COMPONENTS = "felix6874.components";

    /** true if our DependencyManager uses the service registry cache (its bundle context is an interceptor) */
    public static volatile boolean s_cacheUsed;

    /** true if the client component has been started, meaning its service dependency has been injected */
    public static volatile boolean s_clientStarted;

    @Override
    public void init(BundleContext context, DependencyManager manager) throws Exception {
        s_cacheUsed = manager.getBundleContext() != context;
        if (!Boolean.parseBoolean(context.getProperty(COMPONENTS))) {
            return;
        }

        long id = context.getBundle().getBundleId();
        Hashtable<String, Object> props = new Hashtable<>();
        props.put("user.bundle", id);
        Runnable service = () -> {};
        manager.add(createComponent()
            .setInterface(Runnable.class.getName(), props)
            .setImplementation(service));

        manager.add(createComponent()
            .setImplementation(new Client())
            .add(createServiceDependency().setService(Runnable.class, "(user.bundle=" + id + ")").setRequired(true)));
    }

    public static class Client {
        volatile Runnable m_service; // injected

        void start() {
            s_clientStarted = m_service != null;
        }
    }
}
